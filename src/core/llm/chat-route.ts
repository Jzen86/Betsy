import type { LLMClient } from "./types.js";

/**
 * Разговор идёт на одной модели, работа — на другой.
 *
 * Решение владельца (23.11): «гемини для болтовни, дипсик для работы». Это не
 * вкусовщина: разговор — 12 тысяч токенов промпта на каждую реплику, и на
 * разговорной модели он дешевле и живее, а инструменты требуют модели, которая
 * умеет tool_calls и не срезает служебный блок в прозу.
 *
 * Маршрут появился 20.11 прямо в собранном `dist` и какое-то время жил без
 * исходников — из-за этого его никто не мог починить, когда он начал рвать
 * ответы. Здесь он восстановлен по бандлу и с тех пор правится как код: движок
 * спрашивает `isSmallTalk` один раз на входящее сообщение и, если это болтовня,
 * берёт `llm.rp()` вместо `llm.fast()`.
 *
 * Включается и выключается переменной `BETSY_RP_ROUTER=0` в юните — это
 * страховка на случай, если маршрут снова начнёт мешать: выключить можно за
 * рестарт, не трогая код.
 */
export const RP_ROUTER = process.env.BETSY_RP_ROUTER !== "0";
export const RP_PROVIDER = process.env.BETSY_RP_PROVIDER || "google";
export const RP_MODEL = process.env.BETSY_RP_MODEL || "gemini-3.5-flash";

/**
 * Классификатор, а не сам ответ: одно слово, дешёвая модель.
 *
 * «Сомневаешься — TOOL» намеренно. Ошибка в сторону разговора стоит обрыва
 * ответа на модели без инструментов (она просто не сможет ничего проверить),
 * а ошибка в сторону работы — только лишних токенов.
 */
const RP_CLASSIFY_PROMPT = [
  "Ты классификатор реплик. Ответь ОДНИМ словом.",
  "CHAT — если это обычная болтовня, флирт, ролевая игра, эмоции, вопрос о чувствах/мнении, продолжение светской беседы, и для ответа НЕ нужны инструменты.",
  "TOOL — если нужны действия: посмотреть/проверить/запустить/изменить что-либо, файлы, сервер, терминал, код, картинки, поиск в интернете, напоминания, расписание, память/заметки.",
  "Сомневаешься — отвечай TOOL.",
].join("\n");

/** Длинное сообщение — работа по определению, классификатор не зовём. */
const MAX_CLASSIFY_CHARS = 400;

/**
 * Болтовня ли это.
 *
 * Пустое сообщение считается болтовнёй (отвечать нечем — пусть отвечает
 * разговорная модель). Ошибка классификатора — «работа»: молча уронить ход
 * из-за того, что не удалось спросить у дешёвой модели, хуже, чем ответить
 * обычным маршрутом.
 */
export async function isSmallTalk(llm: LLMClient, text: string): Promise<boolean> {
  const t = String(text ?? "").trim();
  if (!t) return true;
  if (t.length > MAX_CLASSIFY_CHARS) return false;

  const res = await llm.chat([
    { role: "system", content: RP_CLASSIFY_PROMPT },
    { role: "user", content: t.slice(0, MAX_CLASSIFY_CHARS) },
  ]);

  const answer = String(res?.text ?? "").toUpperCase();
  return answer.includes("CHAT") && !answer.includes("TOOL");
}
